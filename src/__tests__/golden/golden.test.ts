import { rmSync } from "node:fs";
import { join } from "node:path";
import { type DescFile, toBinary } from "@bufbuild/protobuf";
import { fileDesc as originalFileDesc } from "@bufbuild/protobuf/codegenv2";
import { base64Decode } from "@bufbuild/protobuf/wire";
import { FileDescriptorProtoSchema } from "@bufbuild/protobuf/wkt";
import { afterAll, describe, expect, it } from "vitest";
import { fileDesc } from "../../runtime.js";
import { bufBuild, generate, makeWorkDir, writeFiles } from "../helpers.js";

const testdataDir = join(import.meta.dirname, "testdata");
const snapshotsDir = join(import.meta.dirname, "__snapshots__");

const protos = bufBuild(testdataDir);
const toGenerate = protos
  .map((f) => f.name)
  .filter((name) => !name.startsWith("google/"));

describe("target=ts", () => {
  it.each(generate(protos, toGenerate))("$name matches the snapshot", async ({
    name,
    content,
  }) => {
    await expect(content).toMatchFileSnapshot(join(snapshotsDir, name));
  });
});

describe("target=js+dts", () => {
  it.each(
    generate(protos, ["simple.proto"], {
      parameter: "target=js+dts",
    }),
  )("$name matches the snapshot", async ({ name, content }) => {
    await expect(content).toMatchFileSnapshot(
      join(snapshotsDir, "js+dts", name),
    );
  });
});

describe("round trip", () => {
  // Evaluate the generated code as an application would, next to what
  // protoc-gen-es itself generates.
  const workDir = makeWorkDir("golden-");
  afterAll(() => rmSync(workDir, { recursive: true, force: true }));
  const files = (original: boolean) =>
    Object.fromEntries(
      generate(protos, toGenerate, { original }).map((f) => [
        f.name,
        f.content,
      ]),
    );
  const original = files(true);
  writeFiles(join(workDir, "original"), original);
  writeFiles(join(workDir, "ours"), files(false));
  const load = (side: string, name: string) =>
    import(join(workDir, side, name)) as Promise<Record<string, unknown>>;
  const descriptorBytes = (file: DescFile) =>
    toBinary(FileDescriptorProtoSchema, file.proto);

  it.each(Object.keys(original))("%s hydrates the same descriptor", async (
    name,
  ) => {
    const [theirs, ours] = [await load("original", name), await load("ours", name)];
    expect(Object.keys(ours)).toEqual(Object.keys(theirs));
    for (const [key, value] of Object.entries(theirs)) {
      const actual = ours[key] as DescFile | { typeName: string };
      if (isFile(value)) {
        expect(descriptorBytes(actual as DescFile)).toEqual(
          descriptorBytes(value),
        );
      } else if (isElement(value)) {
        expect((actual as { typeName: string }).typeName).toBe(value.typeName);
      }
    }
  });

  it.each(Object.keys(original))("%s hydrates from a raw byte string, as generated by earlier versions", async (
    name,
  ) => {
    const b64 = /fileDesc\("([^"]+)"/.exec(original[name])![1];
    const ours = Object.values(await load("ours", name)).find(isFile)!;
    const legacy = fileDesc(
      String.fromCharCode(...base64Decode(b64)),
      ours.dependencies,
    );
    expect(descriptorBytes(legacy)).toEqual(
      descriptorBytes(originalFileDesc(b64, ours.dependencies)),
    );
  });
});

function isFile(value: unknown): value is DescFile {
  return (value as DescFile | undefined)?.kind === "file";
}

function isElement(value: unknown): value is { typeName: string } {
  return typeof (value as { typeName?: unknown } | undefined)?.typeName === "string";
}
