/**
 * Size of every generated `_pb.ts` of a large googleapis package per
 * variant, minified two ways and compressed per file.
 *
 * Usage: pnpm --filter demo file-sizes
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { gzipSync } from "node:zlib";
import { version as esbuildVersion, transform } from "esbuild";
import { BUNDLE_PACKAGE, generateBundleInputs } from "../src/bundle.js";
import { VARIANT_LABELS, type Variant } from "../src/generate.js";
import { GOOGLEAPIS_REV } from "../src/googleapis.js";
import { assertRoundTrip } from "../src/replay-pair.js";

const resultsDir = join(import.meta.dirname, "..", "results");
const SHOWN: Variant[] = [
  "base64",
  "a",
  "b",
  "b-index-manifest-numbers",
  "b-names",
  "b-names-numbers",
];

/**
 * Drop comments, number types, indentation and line breaks, but keep the
 * TypeScript types that generated code declares anyway. Comments are found
 * outside string literals only: descriptor strings contain `/*`, e.g. in
 * HTTP paths such as `projects/*\/locations`.
 */
function strip(code: string): string {
  let out = "";
  for (let i = 0; i < code.length; ) {
    const c = code[i];
    if (c === '"' || c === "'") {
      let j = i + 1;
      while (code[j] !== c) {
        j += code[j] === "\\" ? 2 : 1;
      }
      out += code.slice(i, j + 1);
      i = j + 1;
    } else if (code.startsWith("//", i)) {
      i = code.indexOf("\n", i);
    } else if (code.startsWith("/*", i)) {
      i = code.indexOf("*/", i) + 2;
    } else {
      out += c;
      i++;
    }
  }
  return out
    .replace(/^(export )?type _numbers_[\w$]+ = \{\n[\s\S]*?^\};\n/gm, "")
    .split("\n")
    .map((line) => line.trim())
    .join("");
}

const files = generateBundleInputs({ recursive: true, parameter: "target=ts" });
const rows: Record<string, Record<string, number>> = {};
for (const variant of SHOWN) {
  const sizes = { stripped: 0, strippedGzip: 0, esbuild: 0, esbuildGzip: 0 };
  for (const file of files) {
    const content = file.content[variant];
    const stripped = strip(content);
    const minified = (await transform(content, { loader: "ts", minify: true }))
      .code;
    sizes.stripped += Buffer.byteLength(stripped);
    sizes.strippedGzip += gzipSync(stripped, { level: 9 }).length;
    sizes.esbuild += Buffer.byteLength(minified);
    sizes.esbuildGzip += gzipSync(minified, { level: 9 }).length;
  }
  rows[variant] = sizes;
}
for (const file of files) {
  assertRoundTrip(file.content);
}

const kib = (n: number) => (n / 1024).toFixed(1);
const vs = (n: number, base: number) => {
  const pct = Math.round((n / base - 1) * 100);
  return pct === 0 ? "" : ` (${pct > 0 ? "+" : "−"}${Math.abs(pct)}%)`;
};
const base = rows["base64"];
const md = [
  "<!-- Generated by scripts/file-sizes.ts -->",
  "",
  `Every generated \`_pb.ts\` of \`${BUNDLE_PACKAGE}\` (subpackages included) and its imports except well-known types: ${files.length} files at googleapis@${GOOGLEAPIS_REV.slice(0, 12)}, \`target=ts\`. Sizes in KiB, summed over the files; gzip level 9 per file.`,
  "",
  "- *Stripped*: comments, number types, indentation and line breaks removed; other TypeScript types kept.",
  `- *esbuild*: \`esbuild --minify --loader=ts\` (${esbuildVersion}) per file, which also removes all types and shortens local names.`,
  "",
  "| variant | stripped | stripped, gzip | esbuild | esbuild, gzip |",
  "| --- | --- | --- | --- | --- |",
  ...SHOWN.map((v) => {
    const r = rows[v];
    return `| ${VARIANT_LABELS[v]} | ${kib(r.stripped)}${vs(r.stripped, base.stripped)} | ${kib(r.strippedGzip)}${vs(r.strippedGzip, base.strippedGzip)} | ${kib(r.esbuild)}${vs(r.esbuild, base.esbuild)} | ${kib(r.esbuildGzip)}${vs(r.esbuildGzip, base.esbuildGzip)} |`;
  }),
];
mkdirSync(resultsDir, { recursive: true });
writeFileSync(join(resultsDir, "file-sizes.md"), `${md.join("\n")}\n`);
console.log(md.join("\n"));
