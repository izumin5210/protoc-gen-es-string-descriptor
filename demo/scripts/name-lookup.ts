/**
 * What looking elements up by name instead of by position costs: time to
 * resolve every message once, and memory for the per-file maps.
 *
 * Usage: pnpm --filter demo name-lookup
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  createFileRegistry,
  type DescFile,
  type DescMessage,
  fromBinary,
} from "@bufbuild/protobuf";
import { messageDesc as messageDescByIndex } from "@bufbuild/protobuf/codegenv2";
import { FileDescriptorSetSchema } from "@bufbuild/protobuf/wkt";
import { BUNDLE_PACKAGE, withPackageProtos } from "../src/bundle.js";
import { GOOGLEAPIS_REV } from "../src/googleapis.js";
import { elementsByName } from "../src/names/runtime.js";
import { bufBuild } from "../src/tools.js";

const gc = (globalThis as { gc?: () => void }).gc;
if (gc === undefined) {
  throw new Error("run with node --expose-gc");
}
const resultsDir = join(import.meta.dirname, "..", "results");

// The generated files plus the well-known types that they import.
const image = withPackageProtos(true, (root) => bufBuild(root, BUNDLE_PACKAGE));

function heapDelta<T>(make: () => T): [T, number] {
  gc!();
  const before = process.memoryUsage().heapUsed;
  const value = make();
  gc!();
  return [value, process.memoryUsage().heapUsed - before];
}

const [set, setBytes] = heapDelta(() =>
  fromBinary(FileDescriptorSetSchema, image),
);
const [registry, registryBytes] = heapDelta(() => createFileRegistry(set));
const files = [...registry.files];

interface Target {
  file: DescFile;
  path: number[];
  name: string;
  desc: DescMessage;
}
const targets: Target[] = files.flatMap((file) => {
  const prefix = file.proto.package === "" ? "" : `${file.proto.package}.`;
  const out: Target[] = [];
  const walk = (list: DescMessage[], path: number[]) => {
    list.forEach((desc, i) => {
      const p = [...path, i];
      out.push({
        file,
        path: p,
        name: desc.typeName.slice(prefix.length),
        desc,
      });
      walk(desc.nestedMessages, p);
    });
  };
  walk(file.messages, []);
  return out;
});

/** Median of 11 runs, in ms. */
function time(run: () => void): string {
  const samples: number[] = [];
  for (let i = 0; i < 11; i++) {
    const t0 = performance.now();
    run();
    samples.push(performance.now() - t0);
  }
  return samples.sort((a, b) => a - b)[5].toFixed(2);
}

const byIndex = time(() => {
  for (const t of targets) {
    const [first, ...rest] = t.path;
    if (messageDescByIndex(t.file, first, ...rest) !== t.desc) {
      throw new Error(`index mismatch for ${t.name}`);
    }
  }
});
// Cold: the maps are built from scratch in every run, as on first use.
const byName = time(() => {
  const maps = new Map(files.map((f) => [f, elementsByName(f)]));
  for (const t of targets) {
    if (maps.get(t.file)!.get(t.name) !== t.desc) {
      throw new Error(`name mismatch for ${t.name}`);
    }
  }
});
const [maps, mapBytes] = heapDelta(() => files.map(elementsByName));

const md = [
  "<!-- Generated by scripts/name-lookup.ts -->",
  "",
  `\`${BUNDLE_PACKAGE}\` (subpackages included) with all imports at googleapis@${GOOGLEAPIS_REV.slice(0, 12)}: ${files.length} file descriptors, ${targets.length} messages. Node ${process.version}, median of 11 runs.`,
  "",
  "| | time to resolve every message once | memory |",
  "| --- | --- | --- |",
  `| by index (\`messageDesc(file, 2, 0)\`) | ${byIndex} ms | — |`,
  `| by name, building a map per file first (\`messageDesc(file, "Outer.Inner")\`) | ${byName} ms | ${(mapBytes / 1024).toFixed(0)} KiB for ${maps.length} maps of ${maps.reduce((n, m) => n + m.size, 0)} messages, enums, services and extensions |`,
  `| for comparison: the registry of the same files | — | ${(registryBytes / 1024 / 1024).toFixed(1)} MiB, plus ${(setBytes / 1024 / 1024).toFixed(1)} MiB for the parsed \`FileDescriptorProto\`s it keeps |`,
];
mkdirSync(resultsDir, { recursive: true });
writeFileSync(join(resultsDir, "name-lookup.md"), `${md.join("\n")}\n`);
console.log(md.join("\n"));
